README = '''# FlavorDB view of the core graph

Generated by scripts/build_flavor_layer.py from the current core graph and its
edge-evidence table. Counts and input hashes are in flavor_manifest.json.

Compound IDs use compound::<PubChem CID> in both surfaces. Ingredient IDs are
the live core ingredient IDs. The has_compound rows exactly match the core.
Molecular-sharing rows include explicit shares_flavor edges and additional molecular
assertions attached to other relations through also_shares_flavor. This preserves
both types of evidence when they describe the same ingredient pair.

Use the checked, deduplicating loader:

```python
from scripts.flavor_contract import load_with_flavor
nodes, edges = load_with_flavor(".")
```

The combined topology may have more edges than the core because attached molecular
assertions become explicit shares_flavor triples. Duplicate triples are counted once.
Numerical evidence remains in flavor_edges.parquet and kg_edge_evidence.parquet.
Blind concatenation is not the supported interface.

For old compound::<name> references, use data/kg/compound_id_crosswalk.csv. Five
legacy names map to multiple chemicals; resolve_legacy_compound refuses an ambiguous
lookup. Refer to docs/COMPOUND_ID_MIGRATION.md before reusing stored node identifiers.

This identity repair does not validate food-form mappings or turn molecular presence
into measured dish flavour. The legacy association review remains open. Flavour
descriptors do not establish allergen status, nutrition or substitution suitability.
Read LICENSE; the optional view is not a licence boundary from the core.
'''


def make_view(nodes, edges, evidence):
    compounds = nodes.loc[nodes.type.eq('compound'), ['node_id', 'type', 'name', 'pubchem_id']].copy()
    if compounds.pubchem_id.isna().any() or compounds.pubchem_id.duplicated().any():
        raise ValueError('compound CIDs must be present and unique')
    if not compounds.node_id.eq('compound::' + compounds.pubchem_id.astype(str)).all():
        raise ValueError('core compound IDs have not migrated to PubChem CIDs')
    attrs = evidence.set_index(KEYS).attributes_json.to_dict()
    output = []
    direct = list(edges.loc[edges.rel.isin(['has_compound', 'shares_flavor']), KEYS].itertuples(index=False, name=None))
    attached = [key for key, value in attrs.items() if json.loads(value).get('also_shares_flavor', False)]
    for h, r, t in direct + attached:
        extra = json.loads(attrs.get((h, r, t), '{}'))
        relation = 'shares_flavor' if extra.get('also_shares_flavor', False) else r
        output.append((h, relation, t, extra.get('shared_compounds'), extra.get('jaccard')))
    view = pd.DataFrame(output, columns=KEYS + ['shared_compounds', 'jaccard'])
    if view.duplicated(KEYS).any():
        raise ValueError('duplicate molecular claims require reconciliation')
    live = set(nodes.node_id)
    if not view['head'].isin(live).all() or not view['tail'].isin(live).all():
        raise ValueError('optional view contains dangling endpoints')
    return compounds.sort_values('node_id').reset_index(drop=True), view.sort_values(KEYS).reset_index(drop=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--root', type=Path, default=REPO)
    ap.add_argument('--docs-only', action='store_true')
    args = ap.parse_args()
    out = args.root / 'data/kg_flavor'
    out.mkdir(parents=True, exist_ok=True)
    if not args.docs_only:
        kg = args.root / 'data/kg'
        inputs = ['kg_nodes.parquet', 'kg_edges.parquet', 'kg_edge_evidence.parquet']
        nodes, edges = make_view(*(pd.read_parquet(kg / file) for file in inputs))
        nodes.to_parquet(out / 'flavor_nodes.parquet', index=False, compression='zstd')
        edges.to_parquet(out / 'flavor_edges.parquet', index=False, compression='zstd')
        manifest = {'schema_version': 2, 'identity': 'PubChem CID', 'nodes': len(nodes),
                    'relations': {k: int(v) for k, v in edges.rel.value_counts().items()},
                    'input_sha256': {file: hashlib.sha256((kg / file).read_bytes()).hexdigest() for file in inputs},
                    'mapping_validation': 'legacy mappings; food identity review not completed'}
        (out / 'flavor_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
        print(json.dumps(manifest, indent=2))
    for name, text in [('LICENSE', LICENSE), ('README.md', README)]:
        (out / name).write_text(text, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
